import esbuild from "esbuild";
import fs from "node:fs";
import process from "node:process";

const OUTFILE = "main.js";
const TARGET_WARN_BYTES = 1 * 1024 * 1024; // 1 MB target budget
const HARD_LIMIT_BYTES = 5 * 1024 * 1024; // 5 MB Obsidian Sync ceiling

const args = new Set(process.argv.slice(2));
const checkMode = args.has("--check");
const prod = args.has("production") || args.has("--production") || checkMode;

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin.
*/`;

function verifyBundleSize(outfile) {
  if (!fs.existsSync(outfile)) {
    console.error(`[build] FAIL: expected bundle "${outfile}" was not produced.`);
    process.exit(1);
  }

  const bytes = fs.statSync(outfile).size;
  const kb = (bytes / 1024).toFixed(2);
  const mb = (bytes / (1024 * 1024)).toFixed(3);
  const summary = `[build] ${outfile}: ${kb} KB (${mb} MB, ${bytes} bytes) | target <= 1024 KB | hard limit < 5120 KB`;

  if (bytes >= HARD_LIMIT_BYTES) {
    console.error(`${summary}`);
    console.error(
      `[build] FAIL: ${outfile} exceeds the 5 MB Obsidian Sync limit (${bytes} >= ${HARD_LIMIT_BYTES} bytes).`,
    );
    process.exit(1);
  }

  if (bytes >= TARGET_WARN_BYTES) {
    console.warn(`${summary}`);
    console.warn(
      `[build] WARN: ${outfile} exceeds the 1 MB target size budget (${kb} KB). Review bundled dependencies.`,
    );
    return;
  }

  console.log(`${summary} [OK]`);
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["packages/obsidian-plugin/src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    "@codemirror/*",
    "@lezer/*",
  ],
  format: "cjs",
  target: "es2022",
  platform: "browser",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  minify: prod,
  treeShaking: true,
  outfile: OUTFILE,
});

if (prod) {
  await context.rebuild();
  await context.dispose();
  verifyBundleSize(OUTFILE);
  process.exit(0);
} else {
  await context.watch();
}

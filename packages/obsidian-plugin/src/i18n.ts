export type UiMessage = keyof typeof simplifiedChinese;

export function isSimplifiedChinese(
  locale = typeof getLanguage === "function" ? getLanguage() : "en",
): boolean {
  return /^zh(?:$|[-_]hans(?:$|[-_])|[-_](?:cn|sg)$)/i.test(locale);
}

export function t(message: UiMessage, ...values: (string | number)[]): string {
  const text = isSimplifiedChinese() ? simplifiedChinese[message] : message;
  return values.length
    ? text.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)]))
    : text;
}

